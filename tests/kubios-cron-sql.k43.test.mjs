function installSqlWithStubs() {
  // La imagen vanilla no trae pg_cron/pg_net; los stubs cubren su superficie.
  return SQL
    .replace(/^\s*create extension if not exists pg_cron;\s*$/gim, '')
    .replace(/^\s*create extension if not exists pg_net with schema extensions;\s*$/gim, '')
}

/* ------------------------------------------------------------------------- *
 * 1. Contrato estático SQL <-> README
 * ------------------------------------------------------------------------- */

test('K43 SQL: net.http_post documenta y usa timeout_milliseconds = 30000', () => {
  assert.match(
    SQL,
    /timeout_milliseconds\s*:=\s*30000\b/,
    'el SQL debe pasar timeout_milliseconds := 30000'
  )
  assert.match(
    README,
    /timeout_milliseconds/,
    'el README debe documentar el parámetro timeout_milliseconds'
  )
  assert.match(README, /\b30000\b|\b30\s*s\b/, 'el README debe documentar el valor de 30 s')
  assert.match(README, /pg_net/i)
  assert.match(README, /presupuesto/i)
  assert.match(README, /maxDuration/)
  assert.match(README, /fluid compute/i)
  assert.match(README, /504/)
  assert.match(README, /infinity/i)
  assert.match(README, /no (?:está|esta) desplegad|NO desplegad/i)
})

test('K43 SQL: el cron se programa en Supabase, no con Vercel Cron', () => {
  assert.equal(
    Object.prototype.hasOwnProperty.call(VERCEL, 'crons'),
    false,
    'vercel.json no debe declarar crons de Vercel'
  )
  assert.match(SQL, /cron\.schedule\(/)
  assert.match(SQL, /net\.http_post/)
  assert.match(SQL, /vault\.decrypted_secrets/)
  assert.match(README, /no usa Vercel Cron/i)
})

test('K43 SQL: la función tick no contiene secretos ni URLs literales', () => {
  assert.doesNotMatch(SQL, /vault\.create_secret/i)
  assert.doesNotMatch(
    SQL,
    /authorization'\s*,\s*'bearer\s+[a-z0-9]/i,
    'no debe existir un Bearer literal en el SQL'
  )
  assert.doesNotMatch(SQL, /https:\/\/[a-z0-9.-]+\.(?:com|app|dev)\/api\/cron/i)
  assert.match(SQL, /security definer/i)
  assert.match(SQL, /set search_path = ''/i)
})

/* ------------------------------------------------------------------------- *
 * 2. Ejecución real en PostgreSQL 16 efímero con stubs
 * ------------------------------------------------------------------------- */

const docker = dockerAvailable()

test(
  'K43 SQL en PostgreSQL 16: el tick encola el timeout documentado y no filtra secretos',
  { skip: docker.ok ? false : docker.reason, timeout: 120_000 },
  async () => {
    const container = `k43-kubios-cron-${process.pid}-${Date.now()}`.toLowerCase()
    let started = false

    try {
      const launch = run(
        'docker',
        [
          'run',
          '--rm',
          '-d',
          '--name',
          container,
          '--pull',
          'never',
          '--network',
          'none',
          '-e',
          'POSTGRES_HOST_AUTH_METHOD=trust',
          'postgres:16'
        ],
        { timeout: 60_000 }
      )
      assert.equal(launch.status, 0, `no se pudo iniciar el contenedor: ${launch.stderr}`)
      started = true

      // La imagen oficial arranca un servidor temporal durante la
      // inicialización y luego lo reinicia. Se exigen varias consultas
      // consecutivas correctas para no ejecutar el SQL en esa ventana.
      let consecutive = 0
      let ready = false
      for (let attempt = 0; attempt < 90; attempt += 1) {
        const probe = run(
          'docker',
          [
            'exec',
            '-i',
            container,
            'psql',
            '-U',
            'postgres',
            '-d',
            'postgres',
            '-X',
            '-q',
            '-A',
            '-t',
            '-c',
            'select 1'
          ],
          { timeout: 10_000 }
        )
        if (probe.status === 0 && probe.stdout.trim() === '1') {
          consecutive += 1
          if (consecutive >= 3) {
            ready = true
            break
          }
        } else {
          consecutive = 0
        }
        await new Promise((resolve) => setTimeout(resolve, 500))
      }
      assert.ok(ready, 'PostgreSQL local no estuvo listo a tiempo')

      const install = dockerPsql(container, `${STUB_SQL}\n${installSqlWithStubs()}`)
      assert.equal(
        install.status,
        0,
        `la instalación falló:\n${install.stderr || install.stdout}`
      )

      // Fail-closed antes de sembrar Vault: sin URL no se encola nada.
      const missingUrl = dockerPsql(
        container,
        'select kubios_private.kubios_sync_cron_tick();'
      )
      assert.notEqual(missingUrl.status, 0, 'el tick debe fallar sin kubios_sync_cron_url')
      assert.match(
        `${missingUrl.stderr}\n${missingUrl.stdout}`,
        /kubios_sync_cron_url/,
        'el error debe nombrar el secreto ausente, sin revelar valores'
      )
      assert.equal(
        scalar(container, 'select count(*) from net.http_post_calls;'),
        '0',
        'un tick sin URL no debe encolar'
      )

      const urlOnly = dockerPsql(
        container,
        `insert into vault.decrypted_secrets (name, decrypted_secret)
         values ('kubios_sync_cron_url', '${SYNTHETIC_URL}');`
      )
      assert.equal(urlOnly.status, 0, `no se pudo sembrar la URL: ${urlOnly.stderr}`)

      const missingSecret = dockerPsql(
        container,
        'select kubios_private.kubios_sync_cron_tick();'
      )
      assert.notEqual(missingSecret.status, 0, 'el tick debe fallar sin kubios_sync_cron_secret')
      assert.match(
        `${missingSecret.stderr}\n${missingSecret.stdout}`,
        /kubios_sync_cron_secret/,
        'el error debe nombrar el secreto ausente, sin revelar valores'
      )
      assert.equal(
        scalar(container, 'select count(*) from net.http_post_calls;'),
        '0',
        'un tick sin secreto no debe encolar'
      )

      // URL no HTTPS y secreto con control interno: fallan cerrado sin encolar.
      const invalidScheme = dockerPsql(
        container,
        `update vault.decrypted_secrets
            set decrypted_secret = 'http://cron.invalid/api/cron/kubios-sync'
          where name = 'kubios_sync_cron_url';
         insert into vault.decrypted_secrets (name, decrypted_secret)
         values ('kubios_sync_cron_secret', '${SYNTHETIC_SECRET}');
         select kubios_private.kubios_sync_cron_tick();`
      )
      assert.notEqual(invalidScheme.status, 0, 'el tick debe rechazar una URL no HTTPS')
      assert.match(
        `${invalidScheme.stderr}\n${invalidScheme.stdout}`,
        /must start with https/i,
        'el error debe indicar el requisito HTTPS sin revelar la URL'
      )
      assert.equal(
        scalar(container, 'select count(*) from net.http_post_calls;'),
        '0',
        'un tick con URL no HTTPS no debe encolar'
      )

      const controlSecret = dockerPsql(
        container,
        `update vault.decrypted_secrets
            set decrypted_secret = '${SYNTHETIC_URL}'
          where name = 'kubios_sync_cron_url';
         update vault.decrypted_secrets
            set decrypted_secret = '${SYNTHETIC_SECRET}' || chr(10) || 'x'
          where name = 'kubios_sync_cron_secret';
         select kubios_private.kubios_sync_cron_tick();`
      )
      assert.notEqual(
        controlSecret.status,
        0,
        'el tick debe rechazar un secreto con caracteres de control'
      )
      assert.match(
        `${controlSecret.stderr}\n${controlSecret.stdout}`,
        /control characters/i,
        'el error debe indicar el control interno sin revelar el secreto'
      )
      assert.equal(
        scalar(container, 'select count(*) from net.http_post_calls;'),
        '0',
        'un tick con secreto invalido no debe encolar'
      )

      // Estado valido para el resto de comprobaciones.
      const secrets = dockerPsql(
        container,
        `update vault.decrypted_secrets
            set decrypted_secret = '${SYNTHETIC_SECRET}'
          where name = 'kubios_sync_cron_secret';`
      )
      assert.equal(secrets.status, 0, `no se pudo restaurar el secreto: ${secrets.stderr}`)

      assert.equal(
        scalar(container, 'select count(*) from cron.job where jobname = $$kubios-sync-every-5-minutes$$;'),
        '1'
      )
      assert.equal(
        scalar(
          container,
          'select active from cron.job where jobname = $$kubios-sync-every-5-minutes$$;'
        ),
        'f',
        'el job debe quedar inactivo'
      )
      assert.equal(
        scalar(
          container,
          'select schedule from cron.job where jobname = $$kubios-sync-every-5-minutes$$;'
        ),
        '*/5 * * * *'
      )

      const requested = scalar(
        container,
        'select kubios_private.kubios_sync_cron_tick();'
      )
      assert.match(requested, /^\d+$/, 'el tick debe devolver un request id')

      assert.equal(
        scalar(
          container,
          'select timeout_milliseconds from net.http_post_calls order by id desc limit 1;'
        ),
        String(DOCUMENTED_TIMEOUT_MS)
      )
      assert.equal(
        scalar(container, 'select url from net.http_post_calls order by id desc limit 1;'),
        SYNTHETIC_URL
      )
      assert.equal(
        scalar(
          container,
          "select headers ->> 'Authorization' from net.http_post_calls order by id desc limit 1;"
        ),
        `Bearer ${SYNTHETIC_SECRET}`
      )
      assert.equal(
        scalar(
          container,
          "select headers ->> 'Content-Type' from net.http_post_calls order by id desc limit 1;"
        ),
        'application/json'
      )
      assert.equal(
        scalar(
          container,
          'select body::text from net.http_post_calls order by id desc limit 1;'
        ),
        '{}'
      )

      const prosrc = scalar(
        container,
        "select prosrc from pg_proc where proname = 'kubios_sync_cron_tick';"
      )
      assert.ok(prosrc.length > 0, 'la función tick debe existir')
      assert.ok(
        !prosrc.includes(SYNTHETIC_SECRET) && !prosrc.includes(SYNTHETIC_URL),
        'el cuerpo de la función no debe contener los secretos'
      )

      const command = scalar(
        container,
        "select command from cron.job where jobname = 'kubios-sync-every-5-minutes';"
      )
      assert.ok(
        !command.includes(SYNTHETIC_SECRET) && !command.includes(SYNTHETIC_URL),
        'cron.job.command no debe contener secretos'
      )
      assert.match(command, /kubios_private\.kubios_sync_cron_tick\(\)/)

      assert.equal(
        scalar(
          container,
          "select has_function_privilege('anon', 'kubios_private.kubios_sync_cron_tick()', 'EXECUTE');"
        ),
        'f'
      )
      assert.equal(
        scalar(
          container,
          "select has_function_privilege('service_role', 'kubios_private.kubios_sync_cron_tick()', 'EXECUTE');"
        ),
        'f'
      )
      assert.equal(
        scalar(
          container,
          "select has_function_privilege('postgres', 'kubios_private.kubios_sync_cron_tick()', 'EXECUTE');"
        ),
        't'
      )

      assert.equal(
        scalar(
          container,
          "select prosecdef from pg_proc where proname = 'kubios_sync_cron_tick';"
        ),
        't',
        'el tick debe seguir siendo security definer'
      )
      assert.match(
        scalar(
          container,
          "select array_to_string(proconfig, ',') from pg_proc where proname = 'kubios_sync_cron_tick';"
        ),
        /search_path=/,
        'el tick debe fijar search_path'
      )
    } finally {
      if (started) {
        run('docker', ['rm', '-f', container], { timeout: 30_000 })
      }
    }
  }
)
