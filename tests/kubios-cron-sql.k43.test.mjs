/**
 * Pruebas K43 de `supabase/cron/install_kubios_sync.sql` y del README del cron.
 *
 * Todo es local: no se contacta con Supabase, Vercel ni Kubios, no se leen
 * `.env` ni credenciales reales. La prueba estática siempre se ejecuta; la
 * prueba dinámica usa un PostgreSQL 16 efímero en Docker con `--network none`
 * y `--pull never`, stubs de `cron`, `net` y `vault`, una URL ficticia
 * (`https://cron.invalid/...`) y un secreto sintético sin valor real.
 *
 * Requisitos de la prueba dinámica:
 *   * Docker disponible y la imagen `postgres:16` ya presente (no se descarga).
 *   * Contenedor propio con nombre único; el cleanup solo borra ese nombre.
 *
 * Ejecutar:
 *
 *   node --conditions=react-server \
 *     --disable-warning=MODULE_TYPELESS_PACKAGE_JSON \
 *     --test tests/kubios-cron-sql.k43.test.mjs
 *
 * Si Docker no está disponible, la prueba dinámica se marca como omitida (no
 * como PASS) y se informa del motivo.
 */

import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'

const ROOT = new URL('../', import.meta.url)
const SQL_URL = new URL('supabase/cron/install_kubios_sync.sql', ROOT)
const README_URL = new URL('supabase/cron/README.md', ROOT)
const VERCEL_URL = new URL('vercel.json', ROOT)

const SQL = await readFile(SQL_URL, 'utf8')
const README = await readFile(README_URL, 'utf8')
const VERCEL = JSON.parse(await readFile(VERCEL_URL, 'utf8'))

const SYNTHETIC_URL = 'https://cron.invalid/api/cron/kubios-sync'
const SYNTHETIC_SECRET = 'synthetic-k43-cron-secret-not-real'
const DOCUMENTED_TIMEOUT_MS = 30_000

function run(command, args, options = {}) {
  return spawnSync(command, args, {
    encoding: 'utf8',
    timeout: 60_000,
    maxBuffer: 10 * 1024 * 1024,
    ...options
  })
}

function dockerAvailable() {
  const version = run('docker', ['--version'], { timeout: 10_000 })
  if (version.status !== 0) return { ok: false, reason: 'docker no está disponible' }

  const image = run('docker', ['image', 'inspect', 'postgres:16'], { timeout: 15_000 })
  if (image.status !== 0) {
    return { ok: false, reason: 'la imagen postgres:16 no está presente (no se descarga)' }
  }

  return { ok: true }
}

function dockerPsql(container, sql, extraArgs = []) {
  return run(
    'docker',
    [
      'exec',
      '-i',
      container,
      'psql',
      '-U',
      'postgres',
      '-d',
      'postgres',
      '-X',
      '-v',
      'ON_ERROR_STOP=1',
      '-q',
      ...extraArgs,
      '-f',
      '-'
    ],
    { input: sql, timeout: 60_000 }
  )
}

function scalar(container, sql) {
  const result = run(
    'docker',
    [
      'exec',
      '-i',
      container,
      'psql',
      '-U',
      'postgres',
      '-d',
      'postgres',
      '-X',
      '-q',
      '-A',
      '-t',
      '-v',
      'ON_ERROR_STOP=1',
      '-c',
      sql
    ],
    { timeout: 30_000 }
  )

  if (result.status !== 0) {
    throw new Error(`consulta fallida: ${result.stderr || result.stdout}`)
  }
  return result.stdout.trim()
}

